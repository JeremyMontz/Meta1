#!/usr/bin/env node
/**
 * Contract-test registry generator/validator — tests/build-registry.mjs
 * ============================================================================
 * WHY THIS EXISTS (#317).
 *   The coded contract-test corpus (tests/*.test.mjs) is the CI "teeth" — the
 *   runner discovers files by name and GitHub Actions runs them as a required
 *   check. This script does NOT hold the teeth; it *indexes* them so the site
 *   can surface the corpus (a computed portfolio STATS count today; a Bond
 *   test-cases page, #318, later) and so the human mirror (tests/REGISTRY.md)
 *   can stop being hand-synced.
 *
 * DESIGN — "derive, don't author" (Model A).
 *   The single source of truth is the test files themselves — the same files CI
 *   runs — so the index literally cannot disagree with what ships. Each
 *   *.test.mjs carries a structured header title line:
 *
 *       * <NAME> — <description>  (Tier <N> · <notes> · GH #<ISSUE>)
 *
 *   plus optional override tags anywhere in the top comment:
 *       @highlight: <one-line human summary>   (else the header description)
 *       @issue: <n>                            (else parsed from the title meta)
 *       @tier:  <n>                            (else parsed from the title meta)
 *
 *   From that we EMIT two artifacts, each into a marked block so authored prose
 *   and hand-tuned data around them are never clobbered:
 *       1. window.TESTS  in  data.js         (site data section — consumers read it)
 *       2. a table in     tests/REGISTRY.md  (human mirror; the "Scope &
 *          exemptions" prose below the table stays human-owned)
 *
 * REUSABLE HARNESS.
 *   Everything except parseTestFile() and the two target/marker constants is
 *   domain-agnostic. A future skills registry reuses this shape wholesale: swap
 *   the parser (read SKILL.md frontmatter) and the emitted section name
 *   (window.SKILLS), point it at the skills dir + hands.html's data.
 *
 * MODES.
 *   --write   regenerate both marked blocks in place.
 *   --check   re-derive in memory and diff against the on-disk blocks; exit 1 on
 *             any drift (this is the registry's own CI tooth). Default if no arg.
 *
 * Zero-dep (node stdlib only). Run from repo root: `node tests/build-registry.mjs --check`.
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, basename, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));      // tests/
const ROOT = join(HERE, '..');                            // repo root
const DATA_JS = join(ROOT, 'data.js');
const REGISTRY_MD = join(HERE, 'REGISTRY.md');

const TESTS_START = '// TESTS:GENERATED START';
const TESTS_END = '// TESTS:GENERATED END';
const TABLE_START = '<!-- REGISTRY:TABLE START (generated by build-registry.mjs — do not edit by hand) -->';
const TABLE_END = '<!-- REGISTRY:TABLE END -->';
const CI_START = '// CI:GENERATED START';
const CI_END = '// CI:GENERATED END';

const EMDASH = '—';

function parseTestFile(dir, name) {
  const text = readFileSync(join(dir, name), 'utf8');
  const id = name.replace(/\.test\.mjs$/, '');
  const block = (text.match(/\/\*\*([\s\S]*?)\*\//) || [, ''])[1];

  // Title = first real comment content line (skip dividers and @tag lines).
  let titleLine = '';
  for (const raw of block.split('\n')) {
    const t = raw.replace(/^\s*\*\s?/, '').trim();
    if (!t || /^-{3,}$/.test(t) || t.startsWith('@')) continue;
    titleLine = t;
    break;
  }

  // Split a trailing "(…meta…)" off the title line (may be absent).
  let title = titleLine, meta = '';
  const pm = titleLine.match(/^(.*?)\s*\(([^()]*)\)\s*$/);
  if (pm) { title = pm[1].trim(); meta = pm[2].trim(); }

  let tier = (meta.match(/Tier\s+(\d+)/i) || [])[1];
  let issue = (meta.match(/#(\d+)/) || [])[1];
  let notes = meta
    .replace(/Tier\s+\d+/i, '')
    .replace(/GH\s*#\d+/i, '')
    .replace(/#\d+/, '')
    .split('\u00b7').map(x => x.trim()).filter(Boolean).join(', ');

  const hi = block.match(/@highlight:\s*(.+)/);
  const isOv = block.match(/@issue:\s*(\d+)/);
  const tiOv = block.match(/@tier:\s*(\d+)/);
  if (isOv) issue = isOv[1];
  if (tiOv) tier = tiOv[1];
  const highlight = hi ? hi[1].trim() : title;

  return {
    id, file: `tests/${name}`, title,
    tier: tier ? Number(tier) : null,
    issue: issue ? Number(issue) : null,
    notes, highlight, status: 'live',
  };
}

const CI_YML = join(ROOT, '.github', 'workflows', 'ci.yml');

// Count the CI check-jobs declared in ci.yml (top-level keys under `jobs:`),
// derived so adding/removing a check updates the site stat automatically.
function countCIChecks() {
  const y = readFileSync(CI_YML, 'utf8').split('\n');
  const ji = y.findIndex(l => /^jobs:\s*$/.test(l));
  if (ji === -1) throw new Error('ci.yml: no jobs: block found');
  let n = 0;
  for (let i = ji + 1; i < y.length; i++) {
    if (/^\S/.test(y[i])) break;                 // dedented out of jobs:
    if (/^  [A-Za-z][\w-]*:\s*$/.test(y[i])) n++; // a job key (2-space indent)
  }
  return n;
}

function renderCIBlock(n) {
  return `${CI_START}\nwindow.CI = ${JSON.stringify({ checks: n })};\n${CI_END}`;
}

function collect() {
  return readdirSync(HERE)
    .filter(n => n.endsWith('.test.mjs') && !basename(n).startsWith('_'))
    .sort()
    .map(n => parseTestFile(HERE, n));
}

function renderTestsBlock(entries) {
  const rows = entries.map(e => '  ' + JSON.stringify({
    id: e.id, file: e.file, title: e.title,
    tier: e.tier, issue: e.issue, notes: e.notes,
    highlight: e.highlight, status: e.status,
  })).join(',\n');
  return `${TESTS_START}\nwindow.TESTS = [\n${rows}\n];\n${TESTS_END}`;
}

function cell(s) { return String(s == null ? '' : s).replace(/\|/g, '\\|'); }

function renderTable(entries) {
  const head = '| Test | File | Tier | Issue | Highlight | Status |\n'
             + '| ---- | ---- | ---- | ----- | --------- | ------ |';
  const rows = entries.map(e => `| \`${cell(e.id)}\` | \`${cell(e.file)}\` | ${e.tier ?? '—'} | ${e.issue ? '#' + e.issue : '—'} | ${cell(e.highlight)} | ${cell(e.status)} |`);
  return `${TABLE_START}\n\n${head}\n${rows.join('\n')}\n\n${TABLE_END}`;
}

function spliceMarked(src, startMark, endMark, replacement, insertBeforeRe) {
  const s = src.indexOf(startMark);
  const e = src.indexOf(endMark);
  if (s !== -1 && e !== -1) {
    return src.slice(0, s) + replacement + src.slice(e + endMark.length);
  }
  if (insertBeforeRe) {
    const m = src.match(insertBeforeRe);
    if (m) {
      const at = m.index;
      return src.slice(0, at) + replacement + '\n\n' + src.slice(at);
    }
  }
  throw new Error('markers absent and no insertion anchor matched');
}

function extractMarked(src, startMark, endMark, label) {
  const s = src.indexOf(startMark);
  const e = src.indexOf(endMark);
  if (s === -1 || e === -1) {
    throw new Error(`${label}: generated block markers missing — run "node tests/build-registry.mjs --write" first`);
  }
  return src.slice(s, e + endMark.length);
}

function replaceLegacyTable(md, marked) {
  const lines = md.split('\n');
  let start = lines.findIndex(l => /^\|\s*TC\b/.test(l));
  if (start === -1) throw new Error('REGISTRY.md: no legacy table header found to anchor first-run insertion');
  let end = start;
  while (end < lines.length && lines[end].trim().startsWith('|')) end++;
  return [...lines.slice(0, start), marked, ...lines.slice(end)].join('\n');
}

const mode = process.argv.includes('--write') ? 'write' : 'check';
const entries = collect();
const testsBlock = renderTestsBlock(entries);
const table = renderTable(entries);

if (mode === 'write') {
  let data = readFileSync(DATA_JS, 'utf8');
  const hadMarkers = data.includes(TESTS_START);
  data = spliceMarked(data, TESTS_START, TESTS_END, testsBlock, /\/\/ .*Hard stats/);
  if (!hadMarkers) {
    const header = `// ${EMDASH} TESTS registry (generated by tests/build-registry.mjs from the\n`
      + `// tests/*.test.mjs headers — do not edit by hand; run \`node tests/build-registry.mjs --write\`).\n`
      + `// Indexes the coded contract-test corpus for site consumers (STATS count today,\n`
      + `// Bond test-cases page #318 later). Source of truth = the test files CI runs. ${EMDASH}\n`;
    data = data.replace(TESTS_START, header + TESTS_START);
  }
  const ciBlock = renderCIBlock(countCIChecks());
  data = spliceMarked(data, CI_START, CI_END, ciBlock, /\/\/ .*Hard stats/);
  writeFileSync(DATA_JS, data);

  let md = readFileSync(REGISTRY_MD, 'utf8');
  md = md.includes(TABLE_START) ? spliceMarked(md, TABLE_START, TABLE_END, table) : replaceLegacyTable(md, table);
  writeFileSync(REGISTRY_MD, md);

  console.log(`registry: wrote ${entries.length} entries → data.js window.TESTS + tests/REGISTRY.md table`);
} else {
  const problems = [];
  try {
    const cur = extractMarked(readFileSync(DATA_JS, 'utf8'), TESTS_START, TESTS_END, 'data.js window.TESTS');
    if (cur.trim() !== testsBlock.trim()) problems.push('data.js window.TESTS is stale — run --write');
  } catch (e) { problems.push(e.message); }
  try {
    const cur = extractMarked(readFileSync(DATA_JS, 'utf8'), CI_START, CI_END, 'data.js window.CI');
    if (cur.trim() !== renderCIBlock(countCIChecks()).trim()) problems.push('data.js window.CI is stale — run --write');
  } catch (e) { problems.push(e.message); }
  try {
    const cur = extractMarked(readFileSync(REGISTRY_MD, 'utf8'), TABLE_START, TABLE_END, 'REGISTRY.md table');
    if (cur.trim() !== table.trim()) problems.push('tests/REGISTRY.md table is stale — run --write');
  } catch (e) { problems.push(e.message); }

  if (problems.length) {
    console.error('✗ registry drift:\n  - ' + problems.join('\n  - '));
    process.exit(1);
  }
  console.log(`✓ registry in sync — ${entries.length} test files indexed, data.js + REGISTRY.md match.`);
}
